def strip_no(s):
    """去掉行首序号与括号补充，作为查 MAP 的键。与 dump 时用的规则完全一致。"""
    s = re.sub(r'^\s*\d+[.、]\s*', '', s)
    s = re.sub(r'[（(][^)）]*[)）]', '', s)
    return s.strip()


def lookup(key):
    """精确查、再前缀兜底。

    前缀兜底是为了几行数据本身的瑕疵：考频表里有「函数未定式极限的计算（三种类型：
    0/0、幂指函数、∞-∞，五步法」——右括号缺失，去括号正则匹配不到，会留一截尾巴。
    这类残缺行名不能手写死键，因为原文一改就失效；用唯一前缀匹配更稳。
    """
    if key in MAP:
        return MAP[key]
    cand = [k for k in MAP if key.startswith(k)]
    if len(cand) == 1:
        return MAP[cand[0]]
    return None


def build():
    out = []
    missing, bad, no_kp = [], [], []
    for i, r in enumerate(rows):
        key = strip_no(r['name'])
        target = lookup(key)
        if target is None:
            missing.append((i, key))
            target = []
        badk = [t for t in target if t not in kpname]
        if badk:
            bad.append((i, key, badk))
            target = [t for t in target if t in kpname]
        if not target:
            no_kp.append((i, key))
        out.append({
            'i': i, 'name': r['name'], 'key': key, 'chap': r['chap'],
            'kp': target, 'diff': r['diff'], 'target': r['target'],
            'sc1': int(r['sc1']), 'sc2': int(r['sc2']),
            'sm1': int(r['sm1']), 'sm2': int(r['sm2']),
            'bg1': int(r['bg1']), 'bg2': int(r['bg2']),
        })

    with io.open(os.path.join(DATA, 'kpmap.json'), 'w', encoding='utf-8') as f:
        json.dump({'rows': out}, f, ensure_ascii=False, separators=(',', ':'))

    mapped = [r for r in out if r['kp']]
    covered = set()
    for r in mapped:
        covered |= set(r['kp'])
    print('映射：%d / %d 行有考点' % (len(mapped), len(out)))
    print('覆盖考点：%d / %d' % (len(covered), len(kps)))
    miss = sorted(k['name'] for k in kps if k['name'] not in covered)
    print('\n未覆盖考点（%d 个）：' % len(miss))
    for n in miss:
        print('   ', n)
    if missing:
        print('\n【需补规则】MAP 里没有这个键（%d 行）：' % len(missing))
        for i, k in missing:
            print('    [%d] %s' % (i, k))
    if bad:
        print('\n【考点名写错】%d 行：' % len(bad))
        for i, k, b in bad:
            print('    [%d] %s -> %s' % (i, k[:40], b))

    # 难度分布：进不进映射，不能改变难度标签的整体倾向
    hard_mapped = sum(1 for r in mapped if r['diff'] == '难')
    hard_all = sum(1 for r in out if r['diff'] == '难')
    print('\n难度标签校验：全表「难」占 %d/%d=%.0f%%，映射上的占 %d/%d=%.0f%%'
          % (hard_all, len(out), 100.0 * hard_all / len(out),
             hard_mapped, len(mapped), 100.0 * hard_mapped / max(1, len(mapped))))


if __name__ == '__main__':
    build()
